    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        Category kat = new Category();
        kat.setIdcategory(Integer.parseInt(txtIdCategory.getText()));
        kat.setNama(txtName.getText());
        kat.setKeterangan(txtDescription.getText());
        kat.save();
        txtIdCategory.setText(Integer.toString(kat.getIdcategory()));
        tampilkanData();
    }//GEN-LAST:event_btnSaveActionPerformed

    private void tblCategoryMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCategoryMouseClicked
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel)tblCategory.getModel();
        int row = tblCategory.getSelectedRow();
        
        txtIdCategory.setText(model.getValueAt(row, 0).toString());
        txtName.setText(model.getValueAt(row, 1).toString());
        txtDescription.setText(model.getValueAt(row, 2).toString());
    }//GEN-LAST:event_tblCategoryMouseClicked

