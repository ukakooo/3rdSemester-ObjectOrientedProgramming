    public void tampilkanData() {
        String[] kolom = {"ID", "Nama", "Keterangan"};
        ArrayList<Category> list = new Category().getAll();
        Object rowData[] = new Object[3];
        
        tblCategory.setModel(new DefaultTableModel(new Object[][] {}, kolom));
        
        for (Category kat : list) {
            rowData[0] = kat.getIdcategory();
            rowData[1] = kat.getNama();
            rowData[2] = kat.getKeterangan();
            
            ((DefaultTableModel) tblCategory.getModel()).addRow(rowData);
        }
    }
    
    public void cari(String keyword) {
        String[] kolom = {"ID", "Nama", "Keterangan"};
        ArrayList<Category> list = new Category().search(keyword);
        Object rowData[] = new Object[3];
        
        tblCategory.setModel(new DefaultTableModel(new Object[][] {}, kolom));
        
        for(Category kat : list) {
            rowData[0] = kat.getIdcategory();
            rowData[1] = kat.getNama();
            rowData[2] = kat.getKeterangan();
            
            ((DefaultTableModel) tblCategory.getModel()).addRow(rowData);
        }
    }

